def apply_hu_window(image_hu: np.ndarray, center: float, width: float) -> np.ndarray:
    img_min = center - (width / 2.0)
    img_max = center + (width / 2.0)
    windowed = np.clip(image_hu, img_min, img_max)
    return ((windowed - img_min) / (img_max - img_min) * 255.0).astype(np.uint8)

def create_adaptive_triple_window_ct(image_hu: np.ndarray, body_part: str = "CHEST") -> np.ndarray:
    bp = body_part.upper()
    if any(k in bp for k in ["HEAD", "BRAIN", "SKULL"]):
        ch_r = apply_hu_window(image_hu, center=40.0, width=80.0)
        ch_g = apply_hu_window(image_hu, center=75.0, width=150.0)
        ch_b = apply_hu_window(image_hu, center=600.0, width=2000.0)
    elif any(k in bp for k in ["ABDOMEN", "PELVIS", "LIVER", "KIDNEY"]):
        ch_r = apply_hu_window(image_hu, center=40.0, width=350.0)
        ch_g = apply_hu_window(image_hu, center=60.0, width=150.0)
        ch_b = apply_hu_window(image_hu, center=450.0, width=1500.0)
    elif any(k in bp for k in ["NECK", "THROAT", "PHARYNX", "LARYNX"]):
        ch_r = apply_hu_window(image_hu, center=50.0, width=250.0)
        ch_g = apply_hu_window(image_hu, center=-300.0, width=1000.0)
        ch_b = apply_hu_window(image_hu, center=450.0, width=1500.0)
    else:
        ch_r = apply_hu_window(image_hu, center=450.0, width=1500.0)
        ch_g = apply_hu_window(image_hu, center=40.0, width=350.0)
        ch_b = apply_hu_window(image_hu, center=-600.0, width=1500.0)
    return np.stack([ch_r, ch_g, ch_b], axis=-1)

def process_image_input(filepath: str, max_slices: int = 12) -> Tuple[List[Image.Image], Dict[str, Any]]:
    if not filepath or not os.path.exists(filepath):
        return [], {}

    metadata: Dict[str, Any] = {
        "Filename": os.path.basename(filepath),
        "Modality": "Dermatology / Clinical Photo",
        "BodyPart": "Unspecified",
        "Series": "Standard Image",
        "TotalSlices": 1,
    }

    output_images: List[Image.Image] = []

    if filepath.lower().endswith(".dcm"):
        try:
            import pydicom
            from pydicom.pixel_data_handlers.util import apply_voi_lut

            ds = pydicom.dcmread(filepath, force=True)
            modality = getattr(ds, "Modality", "UNKNOWN").upper()
            body_part = getattr(ds, "BodyPartExamined", getattr(ds, "StudyDescription", "Unspecified Body Region"))
            metadata["Modality"] = modality
            metadata["BodyPart"] = body_part
            metadata["Series"] = getattr(ds, "SeriesDescription", getattr(ds, "ProtocolName", "Standard Diagnostic Series"))

            pixel_array = ds.pixel_array

            if len(pixel_array.shape) == 3:
                total_frames = pixel_array.shape[0]
                metadata["TotalSlices"] = total_frames
                indices = np.linspace(0, total_frames - 1, min(max_slices, total_frames), dtype=int)
                raw_slices = [pixel_array[i].astype(np.float32) for i in indices]
            else:
                metadata["TotalSlices"] = 1
                raw_slices = [pixel_array.astype(np.float32)]

            for slice_arr in raw_slices:
                if modality == "CT":
                    slope = float(getattr(ds, "RescaleSlope", 1.0))
                    intercept = float(getattr(ds, "RescaleIntercept", 0.0))
                    image_hu = slice_arr * slope + intercept
                    if getattr(ds, "PhotometricInterpretation", "") == "MONOCHROME1":
                        image_hu = np.max(image_hu) - image_hu

                    rgb_matrix = create_adaptive_triple_window_ct(image_hu, body_part=body_part)

                elif modality in ["CR", "DX", "XA"]:
                    try:
                        lut_applied = apply_voi_lut(slice_arr, ds)
                        min_v, max_v = np.min(lut_applied), np.max(lut_applied)
                        scaled = ((lut_applied - min_v) / (max_v - min_v) * 255.0).astype(np.uint8) if max_v > min_v else np.zeros_like(lut_applied, dtype=np.uint8)
                    except Exception:
                        min_v, max_v = np.min(slice_arr), np.max(slice_arr)
                        scaled = ((slice_arr - min_v) / (max_v - min_v) * 255.0).astype(np.uint8) if max_v > min_v else np.zeros_like(slice_arr, dtype=np.uint8)
                    
                    if getattr(ds, "PhotometricInterpretation", "") == "MONOCHROME1":
                        scaled = cv2.bitwise_not(scaled)
                    
                    clahe = cv2.createCLAHE(clipLimit=2.0, tileGridSize=(8, 8))
                    enhanced = clahe.apply(scaled)
                    rgb_matrix = cv2.cvtColor(enhanced, cv2.COLOR_GRAY2RGB)

                elif modality == "MR":
                    if getattr(ds, "PhotometricInterpretation", "") == "MONOCHROME1":
                        slice_arr = np.max(slice_arr) - slice_arr
                    p1, p99 = np.percentile(slice_arr, (1.0, 99.5))
                    clipped = np.clip(slice_arr, p1, p99)
                    scaled = ((clipped - p1) / (p99 - p1) * 255.0).astype(np.uint8) if p99 > p1 else np.zeros_like(clipped, dtype=np.uint8)
                    rgb_matrix = cv2.cvtColor(scaled, cv2.COLOR_GRAY2RGB)

                else:
                    min_v, max_v = np.min(slice_arr), np.max(slice_arr)
                    scaled = ((slice_arr - min_v) / (max_v - min_v) * 255.0).astype(np.uint8) if max_v > min_v else np.zeros_like(slice_arr, dtype=np.uint8)
                    rgb_matrix = cv2.cvtColor(scaled, cv2.COLOR_GRAY2RGB) if len(scaled.shape) == 2 else scaled

                pil_img = Image.fromarray(rgb_matrix)
                pil_img.thumbnail((1920, 1920), Image.Resampling.LANCZOS)
                output_images.append(pil_img)

        except ImportError:
            raise ImportError("pydicom is required for DICOM processing. Run: pip install pydicom")
    else:
        pil_img = Image.open(filepath).convert("RGB")
        w, h = pil_img.size
        np_arr = np.array(pil_img)

        is_film_sheet = (h / float(w) > 1.2 or w / float(h) > 1.2) and max(w, h) >= 1000

        if is_film_sheet:
            metadata["Modality"] = "Printed CT / MRI Multi-Slice Lightbox Film Montage"
            metadata["Series"] = "Multi-Panel Photographic Film Sheet"
            
            lab = cv2.cvtColor(np_arr, cv2.COLOR_RGB2LAB)
            l, a, b_ch = cv2.split(lab)
            clahe = cv2.createCLAHE(clipLimit=2.2, tileGridSize=(8, 8))
            enhanced_l = clahe.apply(l)
            enhanced_rgb = cv2.cvtColor(cv2.merge((enhanced_l, a, b_ch)), cv2.COLOR_LAB2RGB)

            full_overview = Image.fromarray(enhanced_rgb)
            full_overview.thumbnail((2048, 2048), Image.Resampling.LANCZOS)
            output_images.append(full_overview)

            top_crop = Image.fromarray(enhanced_rgb[0:int(h * 0.55), 0:w])
            top_crop.thumbnail((1800, 1800), Image.Resampling.LANCZOS)
            output_images.append(top_crop)

            bottom_crop = Image.fromarray(enhanced_rgb[int(h * 0.45):h, 0:w])
            bottom_crop.thumbnail((1800, 1800), Image.Resampling.LANCZOS)
            output_images.append(bottom_crop)
        else:
            pil_img.thumbnail((2048, 2048), Image.Resampling.LANCZOS)
            output_images.append(pil_img)

    return output_images, metadata



def extract_clinical_report(report_path: str, patient_record_index: int = 0) -> Tuple[Optional[str], List[Image.Image]]:
    if not report_path or not os.path.exists(report_path):
        return None, []
    ext = report_path.lower().split(".")[-1]
    filename = os.path.basename(report_path)
    report_images: List[Image.Image] = []

    if ext in ["jpg", "jpeg", "png", "bmp", "tiff", "webp"]:
        try:
            img = Image.open(report_path).convert("RGB")
            img.thumbnail((2048, 2048), Image.Resampling.LANCZOS)
            report_images.append(img)
            return (
                f"SCANNED / PHOTOGRAPHED LABORATORY DOCUMENT ({filename}):\n"
                "- Visual photo/scan of printed laboratory results provided below.\n"
                "- Extract all panel analytes, reference intervals, and flagged values directly from the image.",
                report_images
            )
        except Exception as e:
            logger.warning("Image lab report load failed: %s", e)

    elif ext == "pdf":
        try:
            import pypdf
            reader = pypdf.PdfReader(report_path)
            extracted = [f"--- Page {i+1} ---\n{p.extract_text().strip()}" for i, p in enumerate(reader.pages) if p.extract_text()]
            if extracted and len("\n".join(extracted).strip()) > 30:
                return f"CLINICAL PDF DOCUMENT ({filename}):\n\n" + "\n\n".join(extracted), []
            
            try:
                import pypdfium2
                pdf = pypdfium2.PdfDocument(report_path)
                for page_idx in range(min(4, len(pdf))):
                    page = pdf[page_idx]
                    bitmap = page.render(scale=2.0)
                    pil_img = bitmap.to_pil().convert("RGB")
                    report_images.append(pil_img)
                return (
                    f"SCANNED PDF LABORATORY REPORT ({filename}):\n"
                    "- Scanned document pages rendered as visual inputs below. Extract all test rows and reference ranges.",
                    report_images
                )
            except ImportError:
                return f"CLINICAL PDF ({filename}): Scanned pages detected. Plain text extraction produced limited content.", []
        except Exception as e:
            logger.warning("PDF extraction failed: %s", e)

    elif ext == "csv":
        try:
            df = pd.read_csv(report_path)
            if not df.empty:
                idx = min(max(0, patient_record_index), len(df) - 1)
                row = df.iloc[idx].to_dict()
                summary = [f"- {CLINICAL_ABBREV_MAP.get(str(k).strip().lower(), str(k).strip())}: {v}" 
                           for k, v in row.items() if pd.notna(v)]
                return f"STRUCTURED CLINICAL / FRESENIUS PANEL ({filename} | Record #{idx+1} of {len(df)}):\n" + "\n".join(summary), []
        except Exception as e:
            logger.warning("CSV read error: %s", e)

    elif ext in ["xlsx", "xls"]:
        try:
            xls = pd.ExcelFile(report_path)
            sheet_name = xls.sheet_names[0]
            df = pd.read_excel(report_path, sheet_name=sheet_name)
            if not df.empty:
                idx = min(max(0, patient_record_index), len(df) - 1)
                row = df.iloc[idx].to_dict()
                summary = [f"- {CLINICAL_ABBREV_MAP.get(str(k).strip().lower(), str(k).strip())}: {v}" 
                           for k, v in row.items() if pd.notna(v)]
                return f"EXCEL LABORATORY / DIALYSIS RECORD ({filename} | Sheet: '{sheet_name}' | Row #{idx+1}):\n" + "\n".join(summary), []
        except Exception as e:
            logger.warning("Excel read error: %s", e)

    elif ext in ["txt", "json", "xml", "md"]:
        try:
            with open(report_path, "r", encoding="utf-8", errors="ignore") as f:
                content = f.read().strip()
                return f"CLINICAL / DIALYSIS TEXT REPORT ({filename}):\n{content}", []
        except Exception as e:
            logger.warning("Text read error: %s", e)

    return None, []



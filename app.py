def transcribe_audio_file(file_path: str, language: Optional[SupportedLanguage] = None) -> Optional[str]:
    api_key = os.getenv("GROQ_API_KEY", GROQ_API_KEY)
    if not api_key:
        logger.error("GROQ_API_KEY is missing.")
        return None

    client = OpenAI(base_url="https://api.groq.com/openai/v1", api_key=api_key)
    try:
        kwargs = {"file": open(file_path, "rb"), "model": "whisper-large-v3"}
        if language:
            kwargs["language"] = language

        with kwargs["file"] as audio_file:
            kwargs["file"] = audio_file
            transcription = client.audio.transcriptions.create(**kwargs)
        return transcription.text.strip() if transcription and transcription.text else None
    except Exception as e:
        logger.error(f"Error during audio transcription: {e}")
        return None


def synthesize_doctor_voice(text: str, language: SupportedLanguage = "en") -> Optional[str]:
    """
    Synthesizes speech in the exact selected language.
    Guarantees clean playback starting at 0:00 without leading pauses, clipping, or cache offset issues.
    """
    if not text or text.startswith("Clinical Execution Error") or text.startswith("Authentication Error"):
        return None

    # Strip symbols, bullets, and markdown that cause TTS to start with silence or clip at second 0
    clean_speech = re.sub(r"[\*#`_\[\]\(\)<>\/\\+=@~^{}:;•\-\"']", " ", text)
    clean_speech = " ".join(clean_speech.split()).strip()

    if not clean_speech:
        return None

    valid_lang = language if language in ["en", "de", "es", "ar", "hi"] else "en"

    # High-precision unique timestamp + salt forces browser HTML5 media player to start at 0:00
    temp_dir = tempfile.gettempdir()
    unique_filename = f"aura_{valid_lang}_{uuid.uuid4().hex}_{int(time.time() * 1000)}.mp3"
    output_path = os.path.join(temp_dir, unique_filename)

    try:
        tts = gTTS(text=clean_speech, lang=valid_lang, slow=False)
        tts.save(output_path)
        return output_path
    except Exception as e:
        logger.error(f"TTS generation error for lang '{valid_lang}': {e}")
        try:
            tts = gTTS(text=clean_speech, lang="en", slow=False)
            tts.save(output_path)
            return output_path
        except Exception:
            return None



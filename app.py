class KDIGOEvaluation(BaseModel):
    aki_stage: str
    ckd_stage: str
    dialysis_adequacy_fresenius: str
    is_emergency: bool
    emergency_reasons: List[str]
    contraindicated_drugs: List[str]
    guideline_directives: List[str]

def evaluate_kdigo_metrics(lab_text: Optional[str] = None) -> KDIGOEvaluation:
    if not lab_text:
        return KDIGOEvaluation(
            aki_stage="No Data",
            ckd_stage="No Data",
            dialysis_adequacy_fresenius="No Dialysis Run Log",
            is_emergency=False,
            emergency_reasons=[],
            contraindicated_drugs=["Verify renal clearance before administering NSAIDs, cytotoxic agents, or iodinated contrast."],
            guideline_directives=["Baseline renal panels required for staging."]
        )

    cr_match = re.search(r"(?:serum\s+creatinine|creatinine|\bsc\b)[\w\s\(\)/]*?[\s:=]+([0-9]+(?:\.[0-9]+)?)", lab_text, re.IGNORECASE)
    base_cr_match = re.search(r"(?:baseline\s+creatinine|prior\s+cr)[\w\s\(\)/]*?[\s:=]+([0-9]+(?:\.[0-9]+)?)", lab_text, re.IGNORECASE)
    egfr_match = re.search(r"(?:egfr|gfr)[\w\s\(\)/]*?[\s:=]+([0-9]+(?:\.[0-9]+)?)", lab_text, re.IGNORECASE)
    k_match = re.search(r"(?:potassium|\bpot\b|k\+)[\w\s\(\)/]*?[\s:=]+([0-9]+(?:\.[0-9]+)?)", lab_text, re.IGNORECASE)
    bicarb_match = re.search(r"(?:bicarbonate|hco3|co2)[\w\s\(\)/]*?[\s:=]+([0-9]+(?:\.[0-9]+)?)", lab_text, re.IGNORECASE)
    uacr_match = re.search(r"(?:uacr|albumin[\s\-/]creatinine)[\w\s\(\)/]*?[\s:=]+([0-9]+(?:\.[0-9]+)?)", lab_text, re.IGNORECASE)
    al_match = re.search(r"(?:urine\s+albumin|albumin|proteinuria|\bal\b)[\w\s\(\)/]*?[\s:=]+([0-9]+(?:\.[0-9]+)?)", lab_text, re.IGNORECASE)
    age_match = re.search(r"(?:age)[\w\s\(\)/]*?[\s:=]+([0-9]+(?:\.[0-9]+)?)", lab_text, re.IGNORECASE)
    gender_match = re.search(r"(?:gender|sex)[\w\s\(\)/]*?[\s:=]+(female|f\b|male|m\b)", lab_text, re.IGNORECASE)

    has_diabetes = bool(re.search(r"(?:diabetes|\bdm\b)[^\n\r]*?[\s:=]+(?:yes|true|1|positive)", lab_text, re.IGNORECASE))
    has_htn = bool(re.search(r"(?:hypertension|\bhtn\b)[^\n\r]*?[\s:=]+(?:yes|true|1|positive)", lab_text, re.IGNORECASE))
    has_ckd_history = bool(re.search(r"classification[^\n\r]*?[\s:=]+(?:ckd|chronic kidney disease)", lab_text, re.IGNORECASE))

    ktv_match = re.search(r"(?:kt/v|spkt/v|ekt/v|ktv)[\w\s\(\)/]*?[\s:=]+([0-9]+(?:\.[0-9]+)?)", lab_text, re.IGNORECASE)
    urr_match = re.search(r"(?:urr|urea\s+reduction)[\w\s\(\)/]*?[\s:=]+([0-9]+(?:\.[0-9]+)?)", lab_text, re.IGNORECASE)
    ufr_match = re.search(r"(?:ufr|ultrafiltration\s+rate|uf\s+rate)[\w\s\(\)/]*?[\s:=]+([0-9]+(?:\.[0-9]+)?)", lab_text, re.IGNORECASE)
    total_uf_match = re.search(r"(?:total\s+uf|uf\s+volume|fluid\s+removed)[\w\s\(\)/]*?[\s:=]+([0-9]+(?:\.[0-9]+)?)", lab_text, re.IGNORECASE)
    vp_match = re.search(r"(?:venous\s+pressure|\bvp\b)[\w\s\(\)/]*?[\s:=]+([0-9]+(?:\.[0-9]+)?)", lab_text, re.IGNORECASE)
    ap_match = re.search(r"(?:arterial\s+pressure|\bap\b)[\w\s\(\)/]*?[\s:=]+([-\+]?[0-9]+(?:\.[0-9]+)?)", lab_text, re.IGNORECASE)
    qb_match = re.search(r"(?:qb|blood\s+flow)[\w\s\(\)/]*?[\s:=]+([0-9]+(?:\.[0-9]+)?)", lab_text, re.IGNORECASE)

    has_dialysis_entry = bool(re.search(r"(?:treatment|modality|status|dialysis_type)[^\n\r]*?[\s:=]+(?:hemodialysis|peritoneal dialysis|dialysis|esrd)", lab_text, re.IGNORECASE))
    has_fresenius_machine_run = bool(ktv_match or ufr_match or vp_match or qb_match)
    is_dialysis = has_dialysis_entry or has_fresenius_machine_run

    current_cr = float(cr_match.group(1)) if cr_match else None
    baseline_cr = float(base_cr_match.group(1)) if base_cr_match else None
    egfr_val = float(egfr_match.group(1)) if egfr_match else None
    k_val = float(k_match.group(1)) if k_match else None
    bicarb_val = float(bicarb_match.group(1)) if bicarb_match else None
    uacr_val = float(uacr_match.group(1)) if uacr_match else None
    al_val = float(al_match.group(1)) if al_match else 0.0
    age_val = float(age_match.group(1)) if age_match else 50.0

    is_female = bool(gender_match and gender_match.group(1).lower().startswith('f'))
    if egfr_val is None and current_cr is not None and current_cr > 0:
        k_factor = 0.7 if is_female else 0.9
        alpha = -0.241 if is_female else -0.302
        if (current_cr / k_factor) > 1:
            alpha = -1.200
        mult = 1.012 if is_female else 1.0
        egfr_val = round(142.0 * ((current_cr / k_factor) ** alpha) * (0.9938 ** age_val) * mult, 1)

    emergencies = []
    contraindicated = ["Non-steroidal anti-inflammatory drugs (NSAIDs)"]
    directives = []

    if k_val is not None and k_val >= 6.0:
        emergencies.append(f"Severe Hyperkalemia ({k_val} mEq/L): Immediate IV calcium gluconate, insulin-glucose infusion, urgent nephrology/dialysis.")
    if bicarb_val is not None and bicarb_val < 15.0:
        emergencies.append(f"Severe Metabolic Acidosis (HCO3: {bicarb_val} mEq/L): Urgent nephrology evaluation for buffer therapy/dialysis.")

    dialysis_status = "Not on Active Hemodialysis"
    if is_dialysis:
        dialysis_status = "Fresenius Hemodialysis Session Active"
        if ktv_match:
            ktv = float(ktv_match.group(1))
            if ktv < 1.2:
                directives.append(f"Suboptimal Fresenius Dialysis Adequacy (spKt/V {ktv} < 1.2 target): Evaluate dialyzer surface area, BFR, or access recirculation.")
            else:
                directives.append(f"Adequate Fresenius Dialysis Clearance (spKt/V {ktv} >= 1.2 target).")
        if ufr_match:
            ufr = float(ufr_match.group(1))
            if ufr > 13.0:
                emergencies.append(f"Excessive Ultrafiltration Rate ({ufr} mL/kg/h > 13 target): High risk of intradialytic hypotension and myocardial stunning. Adjust dry weight.")
        if vp_match:
            vp = float(vp_match.group(1))
            if vp > 200.0:
                emergencies.append(f"Venous Pressure Alert ({vp} mmHg > 200 target): Impending circuit clotting or downstream vascular access stenosis.")

    aki_stage = "None"
    if current_cr is not None and baseline_cr is not None and baseline_cr > 0:
        ratio = current_cr / baseline_cr
        delta = current_cr - baseline_cr
        if ratio >= 3.0 or current_cr >= 4.0 or is_dialysis:
            aki_stage = "KDIGO AKI Stage 3"
            emergencies.append("AKI Stage 3: Urgent nephrology/dialysis consultation required.")
        elif ratio >= 2.0:
            aki_stage = "KDIGO AKI Stage 2"
        elif ratio >= 1.5 or delta >= 0.3:
            aki_stage = "KDIGO AKI Stage 1"

    ckd_stage = "Preserved Function / Unstaged"
    if is_dialysis:
        ckd_stage = "KDIGO CKD Stage G5D (End-Stage Renal Disease on Hemodialysis)"
        contraindicated.extend([
            "Linear Gadolinium Contrast (NSF Risk)",
            "Potassium-sparing diuretics",
            "Iodinated IV Contrast unless scheduled for post-dialysis session"
        ])
    elif egfr_val is not None:
        if egfr_val < 15: ckd_stage = "KDIGO CKD Stage G5 (Kidney Failure)"
        elif egfr_val < 30: ckd_stage = "KDIGO CKD Stage G4 (Severely Decreased)"
        elif egfr_val < 45: ckd_stage = "KDIGO CKD Stage G3b (Moderately to Severely Decreased)"
        elif egfr_val < 60: ckd_stage = "KDIGO CKD Stage G3a (Mildly to Moderately Decreased)"
        elif egfr_val < 90: ckd_stage = "KDIGO CKD Stage G2 (Mildly Decreased)"
        else: ckd_stage = "KDIGO CKD Stage G1 (Normal / Preserved)"

    has_proteinuria = (al_val >= 1.0) or (uacr_val is not None and uacr_val >= 30.0)
    if has_proteinuria or has_ckd_history:
        if "Stage G1" in ckd_stage or "Stage G2" in ckd_stage or ckd_stage == "Preserved Function / Unstaged":
            ckd_stage = f"KDIGO CKD Stage G2A2 (eGFR ~{egfr_val or 'Preserved'} mL/min/1.73m²) with Persistent Proteinuria (Albumin Dipstick: {int(al_val)}+)"
        directives.append("Persistent proteinuria confirmed: Initiate nephroprotective ACEi/ARB or SGLT2i therapy per KDIGO 2024.")

    if has_diabetes:
        directives.append("Primary Etiology: Diabetic Nephropathy. Strict glycemic control (HbA1c < 7%) and renal protection indicated.")
    if has_htn:
        directives.append("Blood Pressure Optimization: Target BP < 120/80 mmHg per KDIGO 2024 guidelines.")

    return KDIGOEvaluation(
        aki_stage=aki_stage,
        ckd_stage=ckd_stage,
        dialysis_adequacy_fresenius=dialysis_status,
        is_emergency=len(emergencies) > 0,
        emergency_reasons=emergencies,
        contraindicated_drugs=list(set(contraindicated)),
        guideline_directives=directives
    )



class KDIGOEvaluation(BaseModel):
    aki_stage: str
    ckd_stage: str
    dialysis_adequacy_fresenius: str
    is_emergency: bool
    emergency_reasons: List[str]
    contraindicated_drugs: List[str]
    guideline_directives: List[str]

def evaluate_kdigo_metrics(lab_text: Optional[str] = None) -> KDIGOEvaluation:
    if not lab_text:
        return KDIGOEvaluation(
            aki_stage="No Data",
            ckd_stage="No Data",
            dialysis_adequacy_fresenius="No Dialysis Log Provided",
            is_emergency=False,
            emergency_reasons=[],
            contraindicated_drugs=["Verify baseline renal clearance before administering NSAIDs, cytotoxic agents, or iodinated contrast."],
            guideline_directives=["Baseline renal panels required for staging."]
        )

    cr_match = re.search(r"(?:serum\s+creatinine|\bcreatinine\b|\bsc\b)[\w\s\(\)/]*?[\s:=]+([0-9]+(?:\.[0-9]+)?)", lab_text, re.IGNORECASE)
    base_cr_match = re.search(r"(?:baseline\s+creatinine|prior\s+cr)[\w\s\(\)/]*?[\s:=]+([0-9]+(?:\.[0-9]+)?)", lab_text, re.IGNORECASE)
    egfr_match = re.search(r"(?:egfr|estimated\s+gfr|\bgfr\b)[\w\s\(\)/]*?[\s:=]+([0-9]+(?:\.[0-9]+)?)", lab_text, re.IGNORECASE)
    k_match = re.search(r"(?:potassium|\bpot\b|k\+)[\w\s\(\)/]*?[\s:=]+([0-9]+(?:\.[0-9]+)?)", lab_text, re.IGNORECASE)
    bicarb_match = re.search(r"(?:bicarbonate|hco3|co2)[\w\s\(\)/]*?[\s:=]+([0-9]+(?:\.[0-9]+)?)", lab_text, re.IGNORECASE)
    
    u_al_match = re.search(r"(?:urine\s+albumin|proteinuria|urine\s+protein)[\w\s\(\)/]*?[\s:=]+([0-9]+(?:\.[0-9]+)?)", lab_text, re.IGNORECASE)
    age_match = re.search(r"(?:age)[\w\s\(\)/]*?[\s:=]+([0-9]+(?:\.[0-9]+)?)", lab_text, re.IGNORECASE)
    gender_match = re.search(r"(?:gender|sex)[\w\s\(\)/]*?[\s:=]+(female|f\b|male|m\b)", lab_text, re.IGNORECASE)
    weight_match = re.search(r"(?:dry\s+weight|weight)[\w\s\(\)/]*?[\s:=]+([0-9]+(?:\.[0-9]+)?)", lab_text, re.IGNORECASE)

    has_diabetes = bool(re.search(r"(?:diabetes|\bdm\b)[^\n\r]*?[\s:=]+(?:yes|true|1|positive)", lab_text, re.IGNORECASE))
    has_htn = bool(re.search(r"(?:hypertension|\bhtn\b)[^\n\r]*?[\s:=]+(?:yes|true|1|positive)", lab_text, re.IGNORECASE))
    
    cause_match = re.search(r"(?:kidney failure cause|etiology|primary cause)[\w\s\(\)/]*?[\s:=]+([a-zA-Z\s]+)", lab_text, re.IGNORECASE)
    documented_cause = cause_match.group(1).strip() if cause_match else None

    ktv_match = re.search(r"(?:kt/v|spkt/v|ekt/v|ktv)[\w\s\(\)/]*?[\s:=]+([0-9]+(?:\.[0-9]+)?)", lab_text, re.IGNORECASE)
    ufr_match = re.search(r"(?:ufr|ultrafiltration\s+rate|uf\s+rate)[\w\s\(\)/]*?[\s:=]+([0-9]+(?:\.[0-9]+)?)", lab_text, re.IGNORECASE)
    fluid_removal_match = re.search(r"(?:fluid\s+removal\s+rate)[\w\s\(\)/]*?[\s:=]+([0-9]+(?:\.[0-9]+)?)", lab_text, re.IGNORECASE)
    vp_match = re.search(r"(?:venous\s+pressure|\bvp\b)[\w\s\(\)/]*?[\s:=]+([0-9]+(?:\.[0-9]+)?)", lab_text, re.IGNORECASE)

    has_dialysis_entry = bool(re.search(r"(?:treatment|modality|status|dialysis|vascular access|dialyzer)[^\n\r]*?[\s:=]+(?:hemodialysis|peritoneal|graft|fistula|catheter|low-flux|high-flux|customized)", lab_text, re.IGNORECASE))
    has_fresenius_machine_run = bool(ktv_match or ufr_match or vp_match or fluid_removal_match)
    is_dialysis = has_dialysis_entry or has_fresenius_machine_run

    current_cr = float(cr_match.group(1)) if cr_match else None
    baseline_cr = float(base_cr_match.group(1)) if base_cr_match else None
    egfr_val = float(egfr_match.group(1)) if egfr_match else None
    k_val = float(k_match.group(1)) if k_match else None
    bicarb_val = float(bicarb_match.group(1)) if bicarb_match else None
    u_al_val = float(u_al_match.group(1)) if u_al_match else None
    weight_val = float(weight_match.group(1)) if weight_match else 70.0
    age_val = float(age_match.group(1)) if age_match else 50.0

    is_female = bool(gender_match and gender_match.group(1).lower().startswith('f'))
    if egfr_val is None and current_cr is not None and current_cr > 0:
        k_factor = 0.7 if is_female else 0.9
        alpha = -0.241 if is_female else -0.302
        if (current_cr / k_factor) > 1:
            alpha = -1.200
        mult = 1.012 if is_female else 1.0
        egfr_val = round(142.0 * ((current_cr / k_factor) ** alpha) * (0.9938 ** age_val) * mult, 1)

    emergencies = []
    contraindicated = ["Non-steroidal anti-inflammatory drugs (NSAIDs)"]
    directives = []

    if k_val is not None and k_val >= 6.0:
        emergencies.append(f"Critical Hyperkalemia ({k_val} mEq/L): Immediate IV calcium gluconate, insulin-glucose infusion, urgent dialysis.")
    if bicarb_val is not None and bicarb_val < 15.0:
        emergencies.append(f"Severe Metabolic Acidosis (HCO3: {bicarb_val} mEq/L): Urgent buffer therapy or emergent dialysis.")

    dialysis_status = "Not on Maintenance Dialysis"
    if is_dialysis:
        dialysis_status = "Active Maintenance Hemodialysis Session"
        if ktv_match:
            ktv = float(ktv_match.group(1))
            if ktv < 1.20:
                directives.append(f"Subtarget Dialysis Clearance (spKt/V {ktv} < 1.20 Fresenius standard): Optimize blood flow Qb to 350-400 mL/min, ensure High-flux membrane, or increase session time.")
            else:
                directives.append(f"Adequate Fresenius Clearance Achieved (spKt/V {ktv} >= 1.20).")
        
        ufr_rate = None
        if ufr_match:
            ufr_rate = float(ufr_match.group(1))
        elif fluid_removal_match and weight_val > 0:
            ufr_rate = round(float(fluid_removal_match.group(1)) / weight_val, 2)
            directives.append(f"Normalized Ultrafiltration Rate: {ufr_rate} mL/kg/h.")

        if ufr_rate and ufr_rate > 13.0:
            emergencies.append(f"High Ultrafiltration Rate ({ufr_rate} mL/kg/h > 13.0 target): High risk of myocardial stunning and intradialytic hypotension. Prescribe isothermal dialysate (35.5°C) and adjust dry weight.")

        if vp_match and float(vp_match.group(1)) > 200.0:
            emergencies.append(f"Venous Pressure Alarm ({vp_match.group(1)} mmHg > 200 target): Access outflow stenosis or circuit clotting.")

    aki_stage = "None"
    if current_cr is not None and baseline_cr is not None and baseline_cr > 0:
        ratio = current_cr / baseline_cr
        delta = current_cr - baseline_cr
        if ratio >= 3.0 or current_cr >= 4.0:
            aki_stage = "KDIGO AKI Stage 3"
            emergencies.append("AKI Stage 3: Immediate nephrology and renal replacement therapy evaluation.")
        elif ratio >= 2.0:
            aki_stage = "KDIGO AKI Stage 2"
        elif ratio >= 1.5 or delta >= 0.3:
            aki_stage = "KDIGO AKI Stage 1"

    ckd_stage = "Preserved Function / Unstaged"
    if is_dialysis:
        ckd_stage = "KDIGO CKD Stage G5D (End-Stage Kidney Disease on Maintenance Hemodialysis)"
        contraindicated.extend([
            "Linear Gadolinium Contrast Agents (NSF Boxed Warning)",
            "Potassium-sparing diuretics (Spironolactone, Eplerenone, Amiloride)",
            "Iodinated IV Contrast without coordinated post-scan dialysis scheduling"
        ])
    elif egfr_val is not None:
        if egfr_val < 15: ckd_stage = "KDIGO CKD Stage G5 (Kidney Failure)"
        elif egfr_val < 30: ckd_stage = "KDIGO CKD Stage G4 (Severely Decreased)"
        elif egfr_val < 45: ckd_stage = "KDIGO CKD Stage G3b (Moderately to Severely Decreased)"
        elif egfr_val < 60: ckd_stage = "KDIGO CKD Stage G3a (Mildly to Moderately Decreased)"
        elif egfr_val < 90: ckd_stage = "KDIGO CKD Stage G2 (Mildly Decreased)"
        else: ckd_stage = "KDIGO CKD Stage G1 (Normal / Preserved)"

    if u_al_val is not None and u_al_val >= 1.0:
        directives.append(f"Persistent proteinuria confirmed ({int(u_al_val)}+ dipstick): Initiate nephroprotective ACEi/ARB or SGLT2i.")

    if documented_cause:
        directives.append(f"Documented Primary Etiology: {documented_cause}. Base diagnosis strictly on this primary etiology.")
    elif has_diabetes:
        directives.append("Secondary Diabetic Risk: Strict glycemic control (HbA1c < 7.0%) indicated.")
    if has_htn:
        directives.append("Arterial Pressure Optimization: Target BP < 120/80 mmHg per KDIGO 2024.")

    return KDIGOEvaluation(
        aki_stage=aki_stage,
        ckd_stage=ckd_stage,
        dialysis_adequacy_fresenius=dialysis_status,
        is_emergency=len(emergencies) > 0,
        emergency_reasons=emergencies,
        contraindicated_drugs=list(set(contraindicated)),
        guideline_directives=directives
    )



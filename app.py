# 9. MASTER CLINICAL DECISION SUPPORT ORCHESTRATOR
# =====================================================================
def execute_enterprise_cds(
    patient_text: Optional[str] = None,
    image_filepaths: Optional[Union[str, List[str]]] = None,
    video_filepath: Optional[str] = None,
    report_filepath: Optional[str] = None,
    language: SupportedLanguage = "en",
    csv_patient_index: int = 0,
) -> Dict[str, Any]:
    api_key = os.getenv("GEMINI_API_KEY", GEMINI_API_KEY)
    if not api_key:
        return {"status": "ERROR", "code": "AUTH_CONFIG_MISSING", "message": "Missing GEMINI_API_KEY in environment."}

    trace_id = str(uuid.uuid4())
    start_time = datetime.now(timezone.utc)

    images_list = [image_filepaths] if isinstance(image_filepaths, str) else (image_filepaths or [])
    processed_images: List[Image.Image] = []
    metadata_lines: List[str] = []
    primary_meta = {}

    for path in images_list:
        imgs, meta = process_image_input(path, max_slices=12)
        if imgs:
            processed_images.extend(imgs)
            primary_meta = meta
            metadata_lines.append(
                f"File: {meta['Filename']} | Modality: {meta['Modality']} | "
                f"BodyPart: {meta['BodyPart']} | Series: {meta['Series']} | Extracted Slices: {len(imgs)}/{meta['TotalSlices']}"
            )

    scan_frames = extract_scan_video_slices(video_filepath, target_frames=24) if video_filepath else []
    report_text, report_images = extract_clinical_report(report_filepath, patient_record_index=csv_patient_index)

    kdigo_data = evaluate_kdigo_metrics(report_text)
    renal_safety = evaluate_renal_mri_safety(primary_meta, report_text)

    has_patient_voice = bool(patient_text and patient_text.strip())
    has_image = bool(processed_images)
    has_video = bool(scan_frames)
    has_report = bool(report_text or report_images)

    if not (has_image or has_video or has_report or has_patient_voice):
        return {
            "status": "EMPTY_INPUT",
            "code": "NO_DATA",
            "message": "No clinical data received. Please provide a medical scan, lab report, video, or voice query."
        }

    client = genai.Client(api_key=api_key.strip())
    active_router_model = MODEL_CANDIDATES[0]

    clinical_domain = classify_clinical_domain(
        metadata_lines=metadata_lines,
        has_image=has_image,
        has_video=has_video,
        has_report=has_report,
        primary_meta=primary_meta,
        preview_image=processed_images[0] if processed_images else None,
        client=client,
        model_name=active_router_model
    )
    logger.info("Routing Case [%s] -> Subspecialty Engine: [%s]", trace_id, clinical_domain)

    subspecialist_instruction = SPECIALIST_PROMPTS.get(clinical_domain, SPECIALIST_PROMPTS["THORAX_PULMONARY"])
    target_lang_name = LANGUAGE_NAMES.get(language, "English")

    system_instruction = f"""
{subspecialist_instruction}
Execution Trace: {trace_id}
Assigned Subspecialty: {clinical_domain}

MANDATORY LINGUISTIC & GRAMMAR DIRECTIVE:
1. The user's chosen interaction language is: {target_lang_name} ({language}).
2. You MUST write all textual fields in the response (including 'clinical_synthesis', all 'findings', and especially 'patient_voice_delivery') ENTIRELY in {target_lang_name}.
3. ZERO GRAMMATICAL ERRORS: Ensure native-speaker level fluency, correct grammatical conjugation, appropriate clinical and colloquial vocabulary, and natural prosody in {target_lang_name}. Do NOT generate literal, awkward, or machine-translated phrasing.
4. SPOKEN VOICE BRIEFING RULES:
   - The 'patient_voice_delivery' field MUST contain strictly 12 to 15 natural spoken sentences in {target_lang_name}.
   - Plain text only. All numbers, sides (left/right), dosages, and units MUST be spelled out completely as words in {target_lang_name}.
   - Cover:
     a. Clear plain-language diagnosis of all present findings.
     b. Bedside stabilization, positioning, sling/splinting, or skin care instructions.
     c. Safe analgesic and therapeutic alternatives (e.g., acetaminophen; topical therapies).
     d. Absolute drug contraindications (strict ban on NSAIDs in renal failure; anticoagulants in cSS).
     e. Critical emergency red-flag symptoms.
"""

    contents: List[Any] = [system_instruction]
    contents.append(f"METADATA CONTEXT:\n- Domain: {clinical_domain}\n- Visual Scans: {len(processed_images)}\n- Parameters: {'; '.join(metadata_lines) or 'None'}")

    if has_report:
        kdigo_payload = (
            f"DETERMINISTIC KDIGO 2024 / FRESENIUS AUDIT:\n"
            f"- AKI Status: {kdigo_data.aki_stage}\n"
            f"- CKD Classification: {kdigo_data.ckd_stage}\n"
            f"- Fresenius Dialysis Status: {kdigo_data.dialysis_adequacy_fresenius}\n"
            f"- High-Risk Emergencies: {'; '.join(kdigo_data.emergency_reasons) or 'None'}\n"
            f"- Mandatory Contraindications: {'; '.join(kdigo_data.contraindicated_drugs)}\n"
            f"- Guideline Directives: {'; '.join(kdigo_data.guideline_directives) or 'Standard surveillance'}"
        )
        contents.append(kdigo_payload)

        if renal_safety.is_contraindicated:
            contents.append(
                f"MANDATORY CLINICAL SAFETY DIRECTIVE:\n"
                f"{renal_safety.clinical_advisory}\n"
                f"Required Action: Prohibit contrast. Recommend: {renal_safety.recommended_alternative}"
            )

    if has_patient_voice:
        contents.append(f"PATIENT'S SPOKEN COMPLAINT:\n\"{patient_text.strip()}\"")
    if report_text:
        contents.append(report_text)
    contents.extend(report_images)
    for idx, img in enumerate(processed_images):
        contents.append(f"DIAGNOSTIC IMAGE #{idx + 1}:")
        contents.append(img)
    if scan_frames:
        contents.append("CINE / VIDEO KEYFRAMES:")
        contents.extend(scan_frames)

    response = None
    active_model = None
    last_inference_error = None

    for model_name in MODEL_CANDIDATES:
        try:
            logger.info("Submitting clinical inference to [%s] (Trace: %s)...", model_name, trace_id)
            response = client.models.generate_content(
                model=model_name,
                contents=contents,
                config=types.GenerateContentConfig(
                    temperature=0.0,
                    response_mime_type="application/json",
                    response_schema=EnterpriseClinicalResponse,
                    max_output_tokens=8192,
                ),
            )
            if response and response.text:
                active_model = model_name
                break
        except Exception as e:
            logger.warning("Inference execution failed on [%s]: %s. Testing fallback...", model_name, e)
            last_inference_error = e

    if not response or not response.text:
        return {
            "status": "ERROR",
            "code": "ALL_MODELS_FAILED",
            "trace_id": trace_id,
            "details": f"Every model in cascade failed. Last error: {str(last_inference_error)}"
        }

    try:
        raw_output = response.text.strip()
        try:
            parsed_data = json.loads(raw_output)
        except Exception:
            logger.warning("JSON truncation detected on [%s]. Running self-healing JSON repair...", active_model)
            repaired_text = repair_truncated_json(raw_output)
            parsed_data = json.loads(repaired_text)

        validated_model = EnterpriseClinicalResponse(**parsed_data)
        validated_dict = validated_model.model_dump()
        hardened_report = run_clinical_safety_assertions(validated_dict)

        duration_ms = (datetime.now(timezone.utc) - start_time).total_seconds() * 1000
        logger.info("Diagnostic completed successfully in %.2f ms via [%s]. Trace: %s", duration_ms, active_model, trace_id)

        return {
            "status": "SUCCESS",
            "model_used": active_model,
            "trace_id": trace_id,
            "timestamp": start_time.isoformat(),
            "execution_duration_ms": duration_ms,
            "clinical_domain": clinical_domain,
            "kdigo_audit": kdigo_data.model_dump(),
            "clinical_decision_support": hardened_report,
            "audio_delivery_script": hardened_report.get("patient_voice_delivery"),
        }

    except ValidationError as ve:
        logger.error("Schema validation failed for trace_id=%s: %s", trace_id, ve)
        return {"status": "ERROR", "code": "SCHEMA_VALIDATION_ERROR", "trace_id": trace_id, "details": str(ve)}
    except Exception as e:
        logger.error("Response parsing failed for trace_id=%s: %s", trace_id, e)
        return {"status": "ERROR", "code": "PARSING_ERROR", "trace_id": trace_id, "details": str(e)}



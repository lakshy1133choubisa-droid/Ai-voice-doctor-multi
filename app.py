class RenalSafetyAlert(BaseModel):
    is_contraindicated: bool
    risk_level: str
    alert_type: str
    clinical_advisory: str
    recommended_alternative: str

def evaluate_renal_mri_safety(metadata: Dict[str, Any], lab_text: Optional[str] = None) -> RenalSafetyAlert:
    if not lab_text:
        return RenalSafetyAlert(
            is_contraindicated=False,
            risk_level="MODERATE",
            alert_type="UNVERIFIED",
            clinical_advisory="Baseline renal panel not detected. Verify creatinine/eGFR prior to contrast administration.",
            recommended_alternative="Proceed with non-contrast protocols if renal status remains unverified."
        )

    egfr_match = re.search(r"(?:egfr|gfr)[\s:=]+([0-9]+(?:\.[0-9]+)?)", lab_text, re.IGNORECASE)
    is_dialysis = bool(re.search(r"\b(hemodialysis|dialysis|esrd|stage 5)\b", lab_text, re.IGNORECASE))
    egfr_val = float(egfr_match.group(1)) if egfr_match else None

    modality = metadata.get("Modality", "").upper()
    series_name = metadata.get("Series", "").lower()
    has_contrast = bool(re.search(r"(?:contrast|\+c|gad|post)", series_name))

    if (egfr_val is not None and egfr_val < 30.0) or is_dialysis:
        if modality == "MR" and has_contrast:
            return RenalSafetyAlert(
                is_contraindicated=True,
                risk_level="HIGH",
                alert_type="NSF_RISK",
                clinical_advisory=(
                    f"CRITICAL CONTRAINDICATION: Severe renal dysfunction identified (eGFR: {egfr_val or 'ESRD on Dialysis'}). "
                    "Linear gadolinium contrast carries a boxed warning for Nephrogenic Systemic Fibrosis (NSF)."
                ),
                recommended_alternative="Non-contrast multiparametric MRI (DWI, ASL, BOLD) or non-contrast Time-of-Flight MRA (TOF-MRA)."
            )
        elif modality == "CT" and has_contrast:
            return RenalSafetyAlert(
                is_contraindicated=True,
                risk_level="HIGH",
                alert_type="CIN_RISK",
                clinical_advisory=f"HIGH CONTRAST NEPHROPATHY RISK: eGFR {egfr_val or '< 30'} mL/min with iodinated contrast.",
                recommended_alternative="Non-contrast CT, ultrasound, or volume expansion with isotonic saline."
            )

    return RenalSafetyAlert(
        is_contraindicated=False,
        risk_level="LOW",
        alert_type="CLEAR",
        clinical_advisory="Baseline renal function cleared for standard diagnostic protocols.",
        recommended_alternative="Proceed as indicated."
    )



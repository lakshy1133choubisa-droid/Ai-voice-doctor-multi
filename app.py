def run_aura_pipeline(
    audio: Optional[str],
    lang_choice: SupportedLanguage,
    img_input: Optional[str],
    vid_input: Optional[str],
    report_file: Optional[str]
) -> Tuple[str, str, Optional[str]]:
    transcript = None
    if audio and os.path.exists(audio):
        transcript = transcribe_audio_file(audio, language=lang_choice)

    displayed_transcript = transcript if transcript else "Direct evaluation triggered without spoken query."
    patient_query_for_model = transcript if transcript else None

    result = execute_enterprise_cds(
        patient_text=patient_query_for_model,
        image_filepaths=img_input,
        video_filepath=vid_input,
        report_filepath=report_file,
        language=lang_choice
    )

    if result.get("status") == "EMPTY_INPUT":
        empty_voice_text = EMPTY_INPUT_ALERTS.get(lang_choice, EMPTY_INPUT_ALERTS["en"])
        clinical_display = f"⚠️ {empty_voice_text}"
        audio_output_path = synthesize_doctor_voice(text=empty_voice_text, language=lang_choice)
        return displayed_transcript, clinical_display, audio_output_path

    if result.get("status") == "SUCCESS":
        report = result["clinical_decision_support"]
        synthesis = report["clinical_synthesis"]

        formatted_report = (
            f"=== CLINICAL DECISION SUPPORT REPORT (Trace ID: {result['trace_id'][:8]}) ===\n\n"
            f"EVALUATION QUALITY: {report['study_evaluation_quality']}\n"
            f"CLINICAL DOMAIN: {result.get('clinical_domain', 'Universal Assessment')}\n"
            f"UNVISUALIZED BLIND SPOTS: {', '.join(report['unvisualized_blind_spots']) or 'None Identified'}\n\n"
            f"PRIMARY DIAGNOSIS:\n• {synthesis['primary_diagnosis']}\n\n"
            f"DIFFERENTIAL DIAGNOSES:\n• " + "\n• ".join(synthesis['differential_diagnoses']) + "\n\n"
            f"PERTINENT NEGATIVES:\n• " + "\n• ".join(synthesis['pertinent_negatives']) + "\n\n"
            f"OBJECTIVE FINDINGS:\n"
        )
        for f in report["findings"]:
            formatted_report += f"• [{f['anatomical_site']}] {f['finding_type']} (Confidence: {f['confidence']*100:.1f}%): {f['details']}\n"

        formatted_report += (
            f"\nHARDWARE AUDIT:\n"
            f"• Type: {report['hardware_evaluation']['hardware_type']}\n"
            f"• Verified Intravascular: {report['hardware_evaluation']['is_invasive_intravascular']}\n"
            f"• Verified Tip Location: {report['hardware_evaluation']['tip_location_verified']}\n\n"
            f"IMMEDIATE BEDSIDE STABILIZATION:\n• {synthesis['immediate_stabilization']}\n\n"
            f"SPECIALIST REFERRAL:\n• {synthesis['specialist_referral']}\n\n"
            f"ABSOLUTE CONTRAINDICATIONS:\n• " + "\n• ".join(synthesis['absolute_contraindications']) + "\n\n"
            f"EMERGENCY RED FLAGS:\n• " + "\n• ".join(synthesis['red_flag_warnings'])
        )

        disclaimer = EU_COMPLIANCE_DISCLAIMERS.get(lang_choice, EU_COMPLIANCE_DISCLAIMERS["en"])
        clinical_display = formatted_report + disclaimer

        spoken_script = result.get("audio_delivery_script", synthesis['primary_diagnosis'])
        selected_eu_voice = EU_COMPLIANCE_SPOKEN.get(lang_choice, EU_COMPLIANCE_SPOKEN["en"])
        complete_spoken_text = f"{spoken_script} {selected_eu_voice}"

        audio_output_path = synthesize_doctor_voice(text=complete_spoken_text, language=lang_choice)

    else:
        clinical_display = f"Clinical Execution Error [{result.get('code', 'UNKNOWN')}]: {result.get('message') or result.get('details')}"
        audio_output_path = None

    return displayed_transcript, clinical_display, audio_output_path



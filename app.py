def repair_truncated_json(json_str: str) -> str:
    s = json_str.strip()
    try:
        json.loads(s)
        return s
    except Exception:
        pass

    in_string = False
    escape = False
    for char in s:
        if char == '\\' and not escape:
            escape = True
            continue
        if char == '"' and not escape:
            in_string = not in_string
        escape = False
    
    if in_string:
        s += '"'
    
    stack = []
    in_string = False
    escape = False
    for char in s:
        if char == '\\' and not escape:
            escape = True
            continue
        if char == '"' and not escape:
            in_string = not in_string
            escape = False
            continue
        escape = False
        if not in_string:
            if char in '{[':
                stack.append(char)
            elif char in '}]':
                if stack:
                    top = stack[-1]
                    if (char == '}' and top == '{') or (char == ']' and top == '['):
                        stack.pop()
    
    while stack:
        open_char = stack.pop()
        if open_char == '{':
            s += '}'
        elif open_char == '[':
            s += ']'
            
    return s

def run_clinical_safety_assertions(report_data: Dict[str, Any]) -> Dict[str, Any]:
    hardware = report_data.get("hardware_evaluation", {})
    voice = report_data.get("patient_voice_delivery", "")

    if not hardware.get("is_invasive_intravascular"):
        if re.search(r"\b(cavoatrial|central line|central venous catheter|PICC)\b", voice, re.IGNORECASE):
            logger.warning("SAFETY ASSERTION TRIGGERED: Misidentified surface line detected in voice text. Sanitizing...")
            voice = re.sub(
                r"(central venous catheter|central line|PICC).*?(terminating near the cavoatrial junction|cavoatrial junction)",
                "external surface monitoring line",
                voice,
                flags=re.IGNORECASE
            )

    clean_voice = re.sub(r"[\*#`_\[\]<>]", "", voice)
    clean_voice = " ".join(clean_voice.split())
    report_data["patient_voice_delivery"] = clean_voice

    return report_data



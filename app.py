def classify_clinical_domain(
    metadata_lines: List[str],
    has_image: bool,
    has_video: bool,
    has_report: bool,
    primary_meta: Dict[str, Any],
    preview_image: Optional[Image.Image],
    client: genai.Client,
    model_name: str
) -> str:
    if not (has_image or has_video) and has_report:
        return "NEPHROLOGY_LABS_DIALYSIS"

    meta_str = (" ".join(metadata_lines) + " " + primary_meta.get("BodyPart", "") + " " + primary_meta.get("Modality", "")).lower()

    if any(k in meta_str for k in ["oncology", "cancer", "tumor", "tumour", "malignan", "metastasi", "sarcoma", "lymphoma", "carcinoma", "neoplasm", "biopsy"]):
        return "ONCOLOGY_NEOPLASM"
    if any(k in meta_str for k in ["brain", "head", "skull", "cervical", "neuro", "swi", "mra"]):
        return "NEURO_HEAD_NECK"
    if any(k in meta_str for k in ["clavicle", "scapula", "femur", "shoulder", "thigh", "knee", "bone"]):
        return "MUSCULOSKELETAL_TRAUMA"
    if any(k in meta_str for k in ["abdomen", "pelvis", "kidney", "renal", "adpkd", "liver"]):
        return "ABDOMEN_PELVIS_RENAL"
    if any(k in meta_str for k in ["chest", "thorax", "lung", "pleura", "mediastin"]):
        return "THORAX_PULMONARY"
    if any(k in meta_str for k in ["derma", "skin", "rash", "lesion", "melanoma", "erythema", "cutaneous", "psoriasis", "urticaria", "acne"]):
        return "DERMATOLOGY_CUTANEOUS"

    if preview_image:
        try:
            router_prompt = (
                "Identify the clinical imaging domain of this medical visual. Reply with ONLY ONE keyword:\n"
                "ONCOLOGY_NEOPLASM\nTHORAX_PULMONARY\nDERMATOLOGY_CUTANEOUS\nNEURO_HEAD_NECK\nABDOMEN_PELVIS_RENAL\nMUSCULOSKELETAL_TRAUMA\nKeyword:"
            )
            res = client.models.generate_content(
                model=model_name,
                contents=[router_prompt, preview_image],
                config=types.GenerateContentConfig(temperature=0.0, max_output_tokens=25)
            )
            detected = res.text.strip().upper()
            for key in ["ONCOLOGY_NEOPLASM", "THORAX_PULMONARY", "DERMATOLOGY_CUTANEOUS", "NEURO_HEAD_NECK", "ABDOMEN_PELVIS_RENAL", "MUSCULOSKELETAL_TRAUMA"]:
                if key in detected:
                    return key
        except Exception as e:
            logger.warning("Visual routing fallback triggered: %s", e)

    return "THORAX_PULMONARY"


